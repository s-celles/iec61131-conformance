#!/usr/bin/env python3
"""Generate the Hugo content of the project site from the repository.

    python3 -I tools/site/sitegen.py --out DIR

writes DIR/content (Markdown pages for Hugo, theme Hextra) and DIR/static
(llms.txt, llms-full.txt). Nothing is written inside the repository: the
pages are derived from conformance/, notes/, the evidence files and the CI
pins on every build, so they cannot drift from them. See tools/site/build.sh.
"""
import argparse
import pathlib
import posixpath
import re
import shutil

REPO = "https://github.com/s-celles/iec61131-conformance"
BLOB = REPO + "/blob/main"

# evidence file stem -> (display name, CI pin variable, section of
# notes/comparison.md with its deviations, or a whole file)
RUNTIMES = {
    "ironplc": ("IronPLC", "IRONPLC_SHA", "notes/findings.md"),
    "matiec": ("matiec", "MATIEC_SHA", "## Where the two runtimes disagree"),
    "openplc": ("OpenPLC's matiec", "OPENPLC_SHA", "## OpenPLC's matiec fork"),
    "strucpp": ("STruC++", "STRUCPP_SHA", "## STruC++ deviations"),
    "rusty": ("RuSTy", "RUSTY_SHA", "## RuSTy deviations"),
    "4diac": ("4diac", "FOURDIAC_VERSION", "## 4diac ("),
    "rk": ("rk", "RK_SHA", "## rk ("),
}
VERDICTS = ("PASS", "FAIL", "SAME", "DIFFERS", "ERROR")
# short forms used in the notes -> GitHub repository
ALIASES = {
    "ironplc": "ironplc/ironplc", "rusty": "PLC-lang/rusty", "STruCpp": "Autonomy-Logic/STruCpp",
    "matiec": "beremiz/matiec", "4diac-ide": "eclipse-4diac/4diac-ide",
    "4diac-forte": "eclipse-4diac/4diac-forte", "rk": "adclz/rk",
}
GENERATED = "<!-- Generated by tools/site/sitegen.py. Edit the source files, not this page. -->\n\n"


# ------------------------------------------------------------------ parsing

def parse_evidence(text):
    """{test path: {"verdict": V, "text": block}} from a *-run.txt file."""
    out = {}
    for block in re.split(r"(?m)^(?=### )", text):
        if not block.startswith("### "):
            continue
        block = re.split(r"(?m)^\d+ tests: ", block)[0].rstrip() + "\n"
        path = block.split("\n", 1)[0][4:].strip()
        m = re.search(r"(?m)^(" + "|".join(VERDICTS) + r") +" + re.escape(path) + r"( .*)?$", block)
        out[path] = {"verdict": m.group(1) if m else "ERROR", "text": block}
    return out


def parse_totals(md):
    m = re.search(r"Totals \((\d+) tests, (\d+) with `status: conformant`\): conformant tests passed, ([^.]*)\.", md)
    passed = {}
    for part in m.group(3).split(";"):
        name, score = part.strip().rsplit(" ", 1)
        passed[name] = int(score.split("/")[0])
    return {"tests": int(m.group(1)), "conformant": int(m.group(2)), "passed": passed}


def between_markers(md, begin="<!-- results:begin -->", end="<!-- results:end -->"):
    return md.split(begin, 1)[1].split(end, 1)[0]


def parse_pins(ci):
    return {k: v for k, v in re.findall(r"(?m)^\s+([A-Z0-9]+_(?:SHA|VERSION)):\s*\"?([^\"\s#]+)\"?", ci)}


def upstream_refs(text):
    refs = set()
    for owner, repo, n in re.findall(r"github\.com/([\w.-]+)/([\w.-]+)/(?:issues|pull)/(\d+)", text):
        refs.add((f"{owner}/{repo}", int(n)))
    for full, n in re.findall(r"(?<![\w/.-])([\w.-]+/[\w.-]+)#(\d+)", text):
        refs.add((full, int(n)))
    for short, n in re.findall(r"(?<![\w/.-])(" + "|".join(map(re.escape, ALIASES)) + r")#(\d+)", text):
        refs.add((ALIASES[short], int(n)))
    return sorted(r for r in refs if "/" in r[0] and not r[0].startswith("."))


def rewrite_links(md, source=""):
    """Relative Markdown links of the repository file `source` -> GitHub."""
    base = posixpath.dirname(source)
    def fix(m):
        target = m.group(2)
        if re.match(r"[a-z]+:|#|/", target):
            return m.group(0)
        return f"{m.group(1)}({BLOB}/{posixpath.normpath(posixpath.join(base, target))})"
    return re.sub(r"(\[[^\]]*\])\(([^)\s]+)\)", fix, md)


def description(st):
    m = re.match(r"\s*\(\*(.*?)\*\)", st, re.S)
    return " ".join(m.group(1).split()) if m else ""


def section(md, heading):
    """The ## section of md whose heading starts with `heading`, without it."""
    lines, out, on = md.split("\n"), [], False
    for line in lines:
        if line.startswith("## "):
            if on:
                break
            on = line.startswith(heading)
            if on:
                out.append(line[3:])
                continue
        if on:
            out.append(line)
    return out[0] if out else "", "\n".join(out[1:]).strip() + "\n"


def drop_title(md):
    return re.sub(r"\A(<p[^\n]*\n\n)?# [^\n]*\n+", "", md)


def demote(md):
    """One heading level down, so a copied file sits under the page title."""
    return re.sub(r"(?m)^(#{1,5}) ", lambda m: "#" + m.group(1) + " ", md)


# ---------------------------------------------------------------- rendering

def front(title, weight=None, **extra):
    lines = ["---", f"title: {quote(title)}", "type: docs"]
    if weight is not None:
        lines.append(f"weight: {weight}")
    for k, v in extra.items():
        lines.append(f"{k}: {quote(v) if isinstance(v, str) else v}")
    return "\n".join(lines + ["---", "", GENERATED])


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def badge(verdict):
    return f"{{{{< badge \"{verdict}\" >}}}}"


def results_rows(table, columns=len(RUNTIMES)):
    """The results table with each test linked to its page and the verdicts
    of the `columns` runtime columns as badges; the note column is kept."""
    out = []
    for line in table.split("\n"):
        cells = line.split(" | ")
        if not line.startswith("| ") or line.startswith("|---") or line.startswith("| test "):
            out.append(line)
            continue
        name = cells[0][2:].strip()
        cells[0] = f"| [{name}]({{{{< relref \"/tests/{name}\" >}}}})"
        for i in range(1, 1 + columns):
            m = re.fullmatch(r"(\*\*)?(" + "|".join(VERDICTS) + r")(\*\*)?( .*)?", cells[i].strip())
            if m:
                cells[i] = badge(m.group(2)) + (m.group(4) or "")
        out.append(" | ".join(cells))
    return "\n".join(out)


def fence(code, lang=""):
    ticks = "````" if "```" in code else "```"
    return f"{ticks}{lang}\n{code.rstrip()}\n{ticks}\n"


class Site:
    def __init__(self, root):
        self.root = pathlib.Path(root)
        self.comparison = (self.root / "notes/comparison.md").read_text()
        self.totals = parse_totals(self.comparison)
        self.pins = parse_pins((self.root / ".github/workflows/ci.yml").read_text())
        self.evidence = {rt: parse_evidence((self.root / f"notes/evidence/{rt}-run.txt").read_text()) for rt in RUNTIMES}
        self.tests = sorted(p.relative_to(self.root).as_posix() for p in self.root.glob("conformance/*/*.st"))
        notes = [self.comparison, (self.root / "notes/findings.md").read_text(), (self.root / "upstream-bugs.md").read_text()]
        notes += [p.read_text() for p in sorted(self.root.glob("notes/fuzz-*.md"))]
        self.refs = upstream_refs("\n".join(notes))

    def read(self, rel):
        return (self.root / rel).read_text()

    def pin(self, rt):
        v = self.pins.get(RUNTIMES[rt][1], "?")
        return v[:7] if re.fullmatch(r"[0-9a-f]{40}", v) else v

    def passed(self, rt):
        return self.totals["passed"].get(RUNTIMES[rt][0], 0)

    # pages
    def home(self):
        t = self.totals
        rows = "\n".join(f"| [{name}]({{{{< relref \"/runtimes/{rt}\" >}}}}) | `{self.pin(rt)}` | {self.passed(rt)} / {t['conformant']} |"
                         for rt, (name, _, _) in RUNTIMES.items())
        return front("IEC 61131-3 conformance traces", 0) + f"""<div class="project-kicker">IEC 61131-3 · Structured Text · hand-derived traces</div>

**An open, runtime-agnostic conformance suite for IEC 61131-3 Structured Text runtimes.**

Plain `.st` programs paired with plain-text expected input/output traces, one record per scan cycle, derived by hand from the text of the standard (editions 2 and 3) and run against seven runtimes through simulated-clock harnesses. A Lean 4 model proves that the function block traces follow from the standard's bodies. Public domain (CC0 1.0).

{{{{< stats tests="{t['tests']}" conformant="{t['conformant']}" runtimes="{len(RUNTIMES)}" upstream="{len(self.refs)}" >}}}}

[Browse the results →]({{{{< relref "/results" >}}}}) · [Read a test →]({{{{< relref "/tests" >}}}}) · [Upstream issues →]({{{{< relref "/upstream" >}}}}) · [Trace format →]({{{{< relref "/docs/spec" >}}}})

## Conformant tests passed

Counts are recomputed from `notes/comparison.md` on every build. They are not a ranking: the runtimes target different editions and scopes, and some failures are missing features rather than wrong answers.

| Runtime | Pinned | Passed |
|---|---|---:|
{rows}

## What the results mean

A runtime that fails a trace is a claim to verify against the cited clause, not a verdict. `status: implementation-defined` traces record one runtime's choice where the standard leaves the value open; `SAME`/`DIFFERS` only says whether another runtime made the same choice. `ERROR` is a limit of the harness or of the build. The results are for the pinned commits. See [the method]({{{{< relref "/docs/guide" >}}}}) for the full statement.
"""

    def results(self):
        table = results_rows(between_markers(self.comparison))
        return front("Results", 1) + "Every test on every runtime, from `notes/comparison.md` (regenerated from the evidence files by `harness/summarize.py`; the note column is hand-written).\n\n" + rewrite_links(table.strip()) + "\n"

    def test_page(self, path):
        st = self.read(path)
        trace = self.read(path[:-3] + ".trace")
        cat, name = path.split("/")[1], pathlib.Path(path).stem
        rows, details = [], []
        for rt, (rname, _, _) in RUNTIMES.items():
            e = self.evidence[rt].get(path)
            v = e["verdict"] if e else "ERROR"
            rows.append(f"| {rname} | {badge(v)} |")
            if e:
                details.append(f"<details><summary>{rname}: {v}</summary>\n\n{fence(e['text'])}\n</details>\n")
        status = re.search(r"(?m)^status: *(\S+)", trace)
        desc = description(st)
        return (front(f"{cat}/{name}", linkTitle=name, description=desc or name) +
                f"{desc}\n\nStatus: `{status.group(1) if status else '?'}` · [source]({BLOB}/{path}) · [trace]({BLOB}/{path[:-3]}.trace)\n\n"
                "| Runtime | Result |\n|---|---|\n" + "\n".join(rows) + "\n\n## Program\n\n" + fence(st, "iecst") +
                "\n## Expected trace\n\n" + fence(trace) + "\n## Recorded output\n\n" + "\n".join(details))

    def tests_index(self):
        out = [front("Tests", 2), f"{len(self.tests)} tests in {len({p.split('/')[1] for p in self.tests})} directories. Each page shows the program, its hand-derived trace and what every pinned runtime produced.\n"]
        short = {rt: RUNTIMES[rt][0] for rt in RUNTIMES}
        for cat in sorted({p.split("/")[1] for p in self.tests}):
            out.append(f"\n## {cat}\n\n| Test | " + " | ".join(short.values()) + " |\n|---|" + "---|" * len(short))
            for p in (p for p in self.tests if p.split("/")[1] == cat):
                stem = pathlib.Path(p).stem
                cells = " | ".join(badge(self.evidence[rt].get(p, {}).get("verdict", "ERROR")) for rt in RUNTIMES)
                out.append(f"| [{stem}]({{{{< relref \"/tests/{cat}/{stem}\" >}}}}) | {cells} |")
        return "\n".join(out) + "\n"

    def runtime_page(self, rt, weight):
        name, _, src = RUNTIMES[rt]
        if src.endswith(".md"):
            heading, body = name, drop_title(self.read(src))
        else:
            heading, body = section(self.comparison, src)
        ev = self.read(f"notes/evidence/{rt}-run.txt")
        summary = re.search(r"(?m)^\d+ tests: .*$", ev)
        return (front(name, weight) + f"Pinned: `{self.pins.get(RUNTIMES[rt][1], '?')}` · conformant tests passed: {self.passed(rt)} / {self.totals['conformant']} · "
                f"[evidence]({BLOB}/notes/evidence/{rt}-run.txt) (`{summary.group(0) if summary else ''}`)\n\n"
                f"## {heading}\n\n" + demote(rewrite_links(body, src if src.endswith(".md") else "notes/comparison.md")))

    def upstream(self):
        out = [front("Upstream", 4), f"{len(self.refs)} upstream issues and pull requests cited in the notes, by repository. Their state is on GitHub; the notes say what each one covers.\n"]
        for repo in sorted({r for r, _ in self.refs}, key=str.lower):
            nums = [n for r, n in self.refs if r == repo]
            out.append(f"\n## {repo}\n\n" + " · ".join(f"[#{n}](https://github.com/{repo}/issues/{n})" for n in nums))
        return "\n".join(out) + "\n"

    def doc(self, rel, title, weight):
        return front(title, weight) + f"From [`{rel}`]({BLOB}/{rel}).\n\n" + demote(rewrite_links(drop_title(self.read(rel)), rel))

    def docs(self):
        pages = {"guide": ("docs/guide.md", "Guide"), "spec": ("SPEC.md", "Trace format"),
                 "upstream-drafts": ("upstream-bugs.md", "Upstream drafts"), "changelog": ("CHANGELOG.md", "Changelog")}
        for i, p in enumerate(sorted(self.root.glob("notes/fuzz-*.md"))):
            pages[p.stem] = (p.relative_to(self.root).as_posix(), "Fuzz " + p.stem[5:])
        return {k: self.doc(rel, title, i + 1) for i, (k, (rel, title)) in enumerate(pages.items())}

    def llms(self):
        t = self.totals
        head = (f"# IEC 61131-3 conformance traces\n\n> Runtime-agnostic conformance suite for IEC 61131-3 Structured Text: "
                f"{t['tests']} .st programs with hand-derived per-cycle traces ({t['conformant']} conformant), run against "
                f"{', '.join(n for n, _, _ in RUNTIMES.values())}. Public domain.\n\n")
        links = "## Pages\n\n" + "".join(f"- [{n}](runtimes/{rt}/): deviations and results\n" for rt, (n, _, _) in RUNTIMES.items())
        links += "- [Results](results/)\n- [Tests](tests/)\n- [Upstream issues](upstream/)\n- [Trace format](docs/spec/)\n"
        full = [head, "## Trace format\n\n", drop_title(self.read("SPEC.md")), "\n## Tests\n"]
        for p in self.tests:
            vs = ", ".join(f"{RUNTIMES[rt][0]} {self.evidence[rt].get(p, {}).get('verdict', 'ERROR')}" for rt in RUNTIMES)
            full.append(f"\n### {p[12:-3]}\n\n{description(self.read(p))}\n\nResults: {vs}\n\n" + fence(self.read(p), "iecst") + "\n" + fence(self.read(p[:-3] + ".trace")))
        return head + links, "".join(full)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def generate(root, out):
    out = pathlib.Path(out)
    site = Site(root)
    for sub in ("content", "static"):
        if (out / sub).exists():
            shutil.rmtree(out / sub)
    c = out / "content"
    write(c / "_index.md", site.home())
    write(c / "results.md", site.results())
    write(c / "tests/_index.md", site.tests_index())
    for cat in sorted({p.split("/")[1] for p in site.tests}):
        write(c / "tests" / cat / "_index.md", front(cat))
    for p in site.tests:
        write(c / "tests" / p.split("/")[1] / (pathlib.Path(p).stem + ".md"), site.test_page(p))
    write(c / "runtimes/_index.md", front("Runtimes", 3) + "Each pinned runtime, how it was run, and the deviations the suite found, from the notes.\n")
    for i, rt in enumerate(RUNTIMES):
        write(c / "runtimes" / f"{rt}.md", site.runtime_page(rt, i + 1))
    write(c / "upstream.md", site.upstream())
    write(c / "docs/_index.md", front("Docs", 5) + "The repository's documents, rendered.\n")
    for k, text in site.docs().items():
        write(c / "docs" / f"{k}.md", text)
    short, full = site.llms()
    write(out / "static/llms.txt", short)
    write(out / "static/llms-full.txt", full)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[2]))
    ap.add_argument("--out", required=True, help="directory for content/ and static/ (outside the repository)")
    a = ap.parse_args()
    generate(a.root, a.out)


if __name__ == "__main__":
    main()
