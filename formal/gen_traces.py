#!/usr/bin/env python3
"""Generates formal/Conformance/Traces.lean from the .trace files.

The Lean data is derived from the trace files, not written by hand, so the
theorems in Proofs.lean are about the very traces the harnesses run.
Run from the suite root:  python3 -I formal/gen_traces.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "harness" / "matiec"))
from tracefmt import parse_trace  # noqa: E402

# test -> (lean name, input encoder, expected-output encoder)
# Inputs are persisted across records exactly as SPEC.md says.

def b(v):
    return "true" if v.v else "false"

def n(v):
    return str(v.v)

def z(v):
    """Int literal; negatives need parentheses after `some`."""
    return f"({v.v})" if v.v < 0 else str(v.v)

def opt(enc, v):
    return "none" if v.kind == "any" else f"some {enc(v)}"

TESTS = {
    "timers/ton": ("ton", ["in"], lambda i: b(i["in"]), ["q", "et"],
                   lambda o: f"({opt(b, o['q'])}, {opt(n, o['et'])})"),
    "timers/tof": ("tof", ["in"], lambda i: b(i["in"]), ["q", "et"],
                   lambda o: f"({opt(b, o['q'])}, {opt(n, o['et'])})"),
    "timers/tp": ("tp", ["in"], lambda i: b(i["in"]), ["q", "et"],
                  lambda o: f"({opt(b, o['q'])}, {opt(n, o['et'])})"),
    "edge/r_trig": ("rTrig", ["clk"], lambda i: b(i["clk"]), ["q"],
                    lambda o: opt(b, o["q"])),
    "edge/f_trig": ("fTrig", ["clk"], lambda i: b(i["clk"]), ["q"],
                    lambda o: opt(b, o["q"])),
    "edge/sr_rs": ("srRs", ["s", "r"], lambda i: f"({b(i['s'])}, {b(i['r'])})", ["q_sr", "q_rs"],
                   lambda o: f"({opt(b, o['q_sr'])}, {opt(b, o['q_rs'])})"),
    "counters/ctu": ("ctu", ["cu", "r"], lambda i: f"({b(i['cu'])}, {b(i['r'])})", ["q", "cv"],
                     lambda o: f"({opt(b, o['q'])}, {opt(n, o['cv'])})"),
    "counters/ctd": ("ctd", ["cd", "ld"], lambda i: f"({b(i['cd'])}, {b(i['ld'])})", ["q", "cv"],
                     lambda o: f"({opt(b, o['q'])}, {opt(z, o['cv'])})"),
    "counters/ctud": ("ctud", ["cu", "cd", "r", "ld"],
                      lambda i: f"({b(i['cu'])}, {b(i['cd'])}, {b(i['r'])}, {b(i['ld'])})",
                      ["qu", "qd", "cv"],
                      lambda o: f"({opt(b, o['qu'])}, {opt(b, o['qd'])}, {opt(z, o['cv'])})"),
}

INPUT_TYPES = {"ton": "Bool", "tof": "Bool", "tp": "Bool", "rTrig": "Bool", "fTrig": "Bool",
               "srRs": "Bool × Bool", "ctu": "Bool × Bool", "ctd": "Bool × Bool",
               "ctud": "Bool × Bool × Bool × Bool"}
OUTPUT_TYPES = {"ton": "Option Bool × Option Nat", "tof": "Option Bool × Option Nat",
                "tp": "Option Bool × Option Nat", "rTrig": "Option Bool", "fTrig": "Option Bool",
                "srRs": "Option Bool × Option Bool", "ctu": "Option Bool × Option Nat",
                "ctd": "Option Bool × Option Int",
                "ctud": "Option Bool × Option Bool × Option Int"}


def initial_inputs(trace, st_text):
    """Declared initial values: every input in these tests is BOOL FALSE or
    has an explicit initialiser we do not use; records set them at cycle 0."""
    return {}


def main():
    out = ["/-! Generated by formal/gen_traces.py from conformance/**/*.trace. Do not edit. -/",
           "namespace Conformance.Traces", ""]
    for test, (name, ins, enc_in, outs, enc_out) in TESTS.items():
        tr = parse_trace((ROOT / "conformance" / f"{test}.trace").read_text())
        cur = {}
        in_lines, out_lines = [], []
        for rec in tr.records:
            for k, v in rec.inputs:
                cur[k] = v
            missing = [k for k in ins if k not in cur]
            if missing:
                raise SystemExit(f"{test}: cycle {rec.cycle} leaves {missing} unset")
            in_lines.append(f"({rec.cycle * tr.period_ms}, {enc_in(cur)})")
            assert rec.expected != "trap"
            o = dict(rec.expected)
            out_lines.append(enc_out(o))
        out.append(f"/-- conformance/{test}.trace: (time ms, inputs) per cycle. -/")
        out.append(f"def {name}Inputs : List (Nat × ({INPUT_TYPES[name]})) :=")
        out.append("  [" + ",\n   ".join(in_lines) + "]")
        out.append("")
        out.append(f"/-- conformance/{test}.trace: expected outputs per cycle (`none` = `?`). -/")
        out.append(f"def {name}Expected : List ({OUTPUT_TYPES[name]}) :=")
        out.append("  [" + ",\n   ".join(out_lines) + "]")
        out.append("")
    out.append("end Conformance.Traces")
    (ROOT / "formal" / "Conformance" / "Traces.lean").write_text("\n".join(out) + "\n")
    print("wrote formal/Conformance/Traces.lean")


if __name__ == "__main__":
    main()
